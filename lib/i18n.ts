export const DICTS: Record<Lang, Dict> = { es, en };
export const dict = (lang: Lang) => DICTS[lang];

/** Pick a language from a cookie value, then the browser's Accept-Language, then Spanish. */
export function pickLang(cookie?: string | null, acceptLanguage?: string | null): Lang {
  if (isLang(cookie)) return cookie;
  const first = (acceptLanguage || "").split(",").map((s) => s.trim().slice(0, 2).toLowerCase());
  for (const code of first) if (isLang(code)) return code;
  return "es";
}
